#---------Ehdollinen toistorakenne------------#
#Alustetaan muuttujat / arvot
hinta = 5
kolikot = 0

#Ehto on kirjoitettu toistolausekkeeseen
while kolikot < hinta:
    #Tapa päivittää ehtoa
    kolikot += 1 #tämä on tässä kohtaa kun tulee muistaa, että ohjelma toistaa while komennon ylhäältä alaspäin 
    print("Annettu", kolikot, "kolikkoa.")

print("Latte maksettu, takka!")
