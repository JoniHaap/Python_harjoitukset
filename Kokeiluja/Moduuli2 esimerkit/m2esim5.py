luku1 = 3
luku2 = 4

#Yhteenlasku
print(luku1 + luku2)

#Vähennyslasku
print(luku1 - luku2)

#Kertolasku
print(luku1 * luku2)

#Normaalijakolasku
print(luku1 / luku2)

#Kokonaislukujakolasku
print(luku1 // luku2)
#vastaus 0 koska 4 ei mene kertaakaan lukuun 3 kokonaislukuna

#Jakojäännös
print(luku1 % luku2)

#Potenssiin korotus
print(luku1 ** luku2)
